/*
  Write the parts of apps/build-bench that repeat per set of entity modules.

  Usage:
    node apps/build-bench/scripts/generate.mjs --sets <n>

  Writes, in apps/build-bench:
    modules.yaml       the shared modules once, then every set's entries
    auth.yaml          every set's user-admin roles, page and endpoint globs
                       and support webhook
    menus.yaml         the demo's menus, plus a menu group per extra set
    policies.yaml      every set's ai-reporting dynamic blocks policy
    sets/set-<k>.yaml  the vars each set passes to the modules/<name>/ vars
                       files: the module entry ids of its own set

  Set 1 keeps the demo's ids. Set k (k >= 2) suffixes each id with "-k". The
  output is plain YAML, checked in; the build never runs this script.
*/

import fs from 'node:fs';
import path from 'node:path';
import { parseArgs } from 'node:util';

const APP_DIRECTORY = path.resolve(import.meta.dirname, '..');
const MODULES_TAG = 'v1.4.1';

// The dependencies each module declares in its manifest at MODULES_TAG.
// Moving to a newer tag means checking these against the new manifests.
const SHARED_MODULES = [
  'layout',
  'user-account',
  'notifications',
  'ai-assistant',
  'events',
  'files',
];
const SET_MODULE_DEPENDENCIES = {
  activities: ['layout', 'events', 'contacts', 'companies', 'files'],
  'ai-reporting': ['layout'],
  companies: ['layout', 'events', 'contacts', 'files'],
  contacts: ['layout', 'events', 'companies', 'files'],
  deals: ['layout', 'events', 'activities', 'files', 'companies', 'contacts', 'workflows'],
  'release-notes': ['layout', 'events', 'notifications', 'files'],
  support: ['layout', 'events', 'notifications', 'files'],
  'user-admin': ['layout', 'events', 'notifications'],
  walkthroughs: [],
  workflows: ['layout', 'events', 'notifications', 'contacts', 'user-account', 'files'],
};
const SET_MODULES = Object.keys(SET_MODULE_DEPENDENCIES);

function readSetCount() {
  const { values } = parseArgs({ options: { sets: { type: 'string' } } });
  const sets = Number(values.sets);
  if (!Number.isInteger(sets) || sets < 1) {
    throw new Error(
      `Usage: node apps/build-bench/scripts/generate.mjs --sets <n>. Received --sets ${JSON.stringify(
        values.sets
      )}.`
    );
  }
  return sets;
}

function getSuffix(set) {
  return set === 1 ? '' : `-${set}`;
}

function getSetIds(set) {
  const ids = {};
  for (const name of SET_MODULES) {
    ids[name] = `${name}${getSuffix(set)}`;
  }
  return ids;
}

function header({ sets }) {
  return [
    `# Generated by scripts/generate.mjs --sets ${sets}. Do not edit by hand:`,
    `# change the script and run \`node apps/build-bench/scripts/generate.mjs --sets ${sets}\`.`,
    '',
  ].join('\n');
}

function source(name) {
  return `"github:lowdefy/modules-mongodb/modules/${name}@${MODULES_TAG}"`;
}

function dependencyLines({ name, set }) {
  const dependencies = SET_MODULE_DEPENDENCIES[name];
  if (dependencies.length === 0) {
    return [];
  }
  const ids = getSetIds(set);
  return [
    '  dependencies:',
    ...dependencies.map((dependency) => `    ${dependency}: ${ids[dependency] ?? dependency}`),
  ];
}

function setVarsLines({ name, set }) {
  return [
    '  vars:',
    '    _ref:',
    `      path: modules/${name}/vars.yaml`,
    '      vars:',
    `        _ref: sets/set-${set}.yaml`,
  ];
}

// One entry per module, in the demo's order: a module entry's vars may _ref
// another module's component, and that module has to be registered first.
function setModuleEntry({ name, set }) {
  const id = `${name}${getSuffix(set)}`;
  const lines = [`- id: ${id}`, `  source: ${source(name)}`, ...dependencyLines({ name, set })];
  switch (name) {
    case 'ai-reporting':
      lines.push(
        '  connections:',
        '    reports-store: reporting-reports',
        '    conversations-store: reporting-conversations',
        '    reporting-data: reporting-analytics',
        ...setVarsLines({ name, set })
      );
      break;
    case 'walkthroughs':
      lines.push('  vars:', '    region: us-east-1', '    writable: true');
      break;
    default:
      lines.push(...setVarsLines({ name, set }));
  }
  return lines.join('\n');
}

function customerUserAdminEntry({ set }) {
  return [
    `- id: customer-user-admin${getSuffix(set)}`,
    `  source: ${source('user-admin')}`,
    ...dependencyLines({ name: 'user-admin', set }),
    '  vars:',
    '    org_slug: customer-portal',
    '    app_title: Customer',
    '    remove_member: false',
    '    delete_user: false',
  ].join('\n');
}

function sharedModuleEntry({ name }) {
  if (name === 'files') {
    return [
      `- id: files`,
      `  source: ${source('files')}`,
      '  vars:',
      '    s3_region: us-east-1',
    ].join('\n');
  }
  return [
    `- id: ${name}`,
    `  source: ${source(name)}`,
    '  vars:',
    `    _ref: modules/${name}/vars.yaml`,
  ].join('\n');
}

// The demo's module order, set modules and shared modules interleaved.
const DEMO_ORDER = [
  'activities',
  'ai-assistant',
  'workflows',
  'companies',
  'contacts',
  'events',
  'files',
  'layout',
  'deals',
  'notifications',
  'release-notes',
  'support',
  'user-account',
  'user-admin',
  'customer-user-admin',
  'ai-reporting',
  'walkthroughs',
];

function entryFor({ name, set }) {
  if (name === 'customer-user-admin') {
    return customerUserAdminEntry({ set });
  }
  if (SHARED_MODULES.includes(name)) {
    return sharedModuleEntry({ name });
  }
  return setModuleEntry({ name, set });
}

function createModulesYaml({ sets }) {
  const blocks = [header({ sets }).trimEnd()];
  blocks.push(
    '# Set 1, with the shared modules, in the demo order: workflows before\n' +
      '# companies, deals after every module it depends on.'
  );
  for (const name of DEMO_ORDER) {
    blocks.push(entryFor({ name, set: 1 }));
  }
  for (let set = 2; set <= sets; set += 1) {
    blocks.push(`# Set ${set}`);
    for (const name of DEMO_ORDER) {
      if (!SHARED_MODULES.includes(name)) {
        blocks.push(entryFor({ name, set }));
      }
    }
  }
  return blocks.join('\n\n') + '\n';
}

function createAuthYaml({ sets }) {
  const roles = [];
  const globs = [];
  const webhooks = [];
  for (let set = 1; set <= sets; set += 1) {
    const suffix = getSuffix(set);
    const label = set === 1 ? '' : ` (set ${set})`;
    roles.push(
      `  - id: user-admin${suffix}`,
      `    label: User Admin${label}`,
      '    description: Administers users across the pinned suite (ban, invite, roles, sessions).',
      `  - id: customer-user-admin${suffix}`,
      `    label: Customer User Admin${label}`,
      '    description: Administers the users of the customer portal organization.'
    );
    globs.push(
      `  user-admin${suffix}:`,
      `    - user-admin${suffix}/**`,
      `  customer-user-admin${suffix}:`,
      `    - customer-user-admin${suffix}/**`
    );
    webhooks.push(`  - support${suffix}/webhook`);
  }
  return [
    header({ sets }),
    '# Read by lowdefy.yaml with _ref key.',
    'roles:',
    ...roles,
    'pages_roles:',
    ...globs,
    'api_roles:',
    ...globs,
    'api_public:',
    ...webhooks,
    '',
  ].join('\n');
}

function createPoliciesYaml({ sets }) {
  const lines = [header({ sets }), '# The dynamic blocks policies, read by lowdefy.yaml.'];
  for (let set = 1; set <= sets; set += 1) {
    lines.push(
      '- _ref:',
      `    module: ${getSetIds(set)['ai-reporting']}`,
      '    component: report-policy'
    );
  }
  return lines.join('\n') + '\n';
}

function moduleMenuRef({ indent, module }) {
  return [`${indent}- _ref:`, `${indent}    module: ${module}`, `${indent}    menu: default`];
}

function moduleMenuLink({ icon, id, module, page, title }) {
  return [
    `            - id: ${id}`,
    '              type: MenuLink',
    '              pageId:',
    '                _module.pageId:',
    `                  module: ${module}`,
    `                  id: ${page}`,
    '              properties:',
    `                title: ${title}`,
    `                icon: ${icon}`,
  ];
}

// The demo's CRM, reporting and admin groups for one extra set, under one group.
function setMenuGroup({ set }) {
  const ids = getSetIds(set);
  return [
    `    - id: set-${set}-group`,
    '      type: MenuGroup',
    '      properties:',
    `        title: Set ${set}`,
    '        icon: Layers',
    '      links:',
    `        - id: crm-group-${set}`,
    '          type: MenuGroup',
    '          properties:',
    '            title: CRM',
    '            icon: Contact',
    '          links:',
    '            _build.array.concat:',
    ...['deals', 'companies', 'contacts', 'activities'].flatMap((name) =>
      moduleMenuRef({ indent: '              ', module: ids[name] })
    ),
    `        - id: reporting-group-${set}`,
    '          type: MenuGroup',
    '          properties:',
    '            title: Reporting',
    '            icon: chart',
    '          links:',
    ...moduleMenuLink({
      icon: 'message',
      id: `reporting-chat-${set}`,
      module: ids['ai-reporting'],
      page: 'chat',
      title: 'Chat',
    }),
    ...moduleMenuLink({
      icon: 'document',
      id: `reporting-reports-${set}`,
      module: ids['ai-reporting'],
      page: 'reports-list',
      title: 'Saved reports',
    }),
    `        - id: admin-group-${set}`,
    '          type: MenuGroup',
    '          properties:',
    '            title: Admin',
    '            icon: settings',
    '          links:',
    '            _ref:',
    `              module: ${ids['user-admin']}`,
    '              menu: default',
  ];
}

function createMenusYaml({ sets }) {
  const template = fs.readFileSync(path.join(APP_DIRECTORY, 'scripts/menus.template.yaml'), 'utf8');
  const setGroups = [];
  for (let set = 2; set <= sets; set += 1) {
    setGroups.push(...setMenuGroup({ set }));
  }
  const marker = '    # {{ set menu groups }}\n';
  if (!template.includes(marker)) {
    throw new Error(`scripts/menus.template.yaml has no "${marker.trim()}" line.`);
  }
  const groups = setGroups.length === 0 ? '' : setGroups.join('\n') + '\n';
  // Lines starting "## " describe the template itself.
  const menus = template
    .split('\n')
    .filter((line) => !line.startsWith('## '))
    .join('\n');
  return header({ sets }) + '\n' + menus.replace(marker, groups);
}

function createSetVarsYaml({ set, sets }) {
  const ids = getSetIds(set);
  return [
    header({ sets }),
    `# Set ${set}: the module entry ids the modules/<name>/vars.yaml files use`,
    '# to reach the other modules of this set.',
    'ids:',
    ...SET_MODULES.map((name) => `  ${name}: ${ids[name]}`),
    '',
  ].join('\n');
}

function writeFile({ content, relativePath }) {
  const filePath = path.join(APP_DIRECTORY, relativePath);
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, content);
}

function main() {
  const sets = readSetCount();
  writeFile({ relativePath: 'modules.yaml', content: createModulesYaml({ sets }) });
  writeFile({ relativePath: 'auth.yaml', content: createAuthYaml({ sets }) });
  writeFile({ relativePath: 'menus.yaml', content: createMenusYaml({ sets }) });
  writeFile({ relativePath: 'policies.yaml', content: createPoliciesYaml({ sets }) });

  const setsDirectory = path.join(APP_DIRECTORY, 'sets');
  fs.rmSync(setsDirectory, { recursive: true, force: true });
  for (let set = 1; set <= sets; set += 1) {
    writeFile({ relativePath: `sets/set-${set}.yaml`, content: createSetVarsYaml({ set, sets }) });
  }
  console.log(
    `Wrote modules.yaml, auth.yaml, menus.yaml, policies.yaml and ${sets} set vars files.`
  );
}

main();
