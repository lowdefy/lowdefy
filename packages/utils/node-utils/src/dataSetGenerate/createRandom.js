// FNV-1a over the key's UTF-16 code units: a 32-bit seed per key, the same on every machine.
function hashKey(key) {
  let hash = 0x811c9dc5;
  for (let index = 0; index < key.length; index += 1) {
    hash ^= key.charCodeAt(index);
    hash = Math.imul(hash, 0x01000193);
  }
  return hash >>> 0;
}

// A seeded random number source (mulberry32): the same key gives the same sequence on every machine
// and every run, which Math.random cannot. Returns a function that gives the next number in [0, 1).
function createRandom({ key }) {
  let state = hashKey(key);
  return function random() {
    state = (state + 0x6d2b79f5) >>> 0;
    let value = state;
    value = Math.imul(value ^ (value >>> 15), value | 1);
    value ^= value + Math.imul(value ^ (value >>> 7), value | 61);
    return ((value ^ (value >>> 14)) >>> 0) / 4294967296;
  };
}

export default createRandom;
