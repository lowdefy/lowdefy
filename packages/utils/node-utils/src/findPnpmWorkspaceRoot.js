import fs from 'fs';
import path from 'path';

// Mirrors how pnpm finds its workspace root: walk up from startDir and return
// the first directory containing pnpm-workspace.yaml, or null if none exists.
function findPnpmWorkspaceRoot(startDir) {
  let dir = startDir;
  while (dir !== path.dirname(dir)) {
    if (fs.existsSync(path.join(dir, 'pnpm-workspace.yaml'))) {
      return dir;
    }
    dir = path.dirname(dir);
  }
  return null;
}

export default findPnpmWorkspaceRoot;
