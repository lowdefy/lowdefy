import path from 'node:path';

import YAML from 'yaml';

import writeFileIfChanged from '../writeFileIfChanged.js';
import moduleLockfileName from './moduleLockfileName.js';

const generatedComment =
  '# This file is generated by the Lowdefy build. Commit it.\n' +
  '# It pins each GitHub module entry to the commit the build fetched.\n';

async function writeModuleLockfile({ configDirectory, lockfile }) {
  const filePath = path.join(configDirectory, moduleLockfileName);
  const sortedIds = Object.keys(lockfile).sort();
  const ordered = {};
  for (const id of sortedIds) {
    const { source, ref, commit } = lockfile[id];
    ordered[id] = { source, ref, commit };
  }

  const content =
    sortedIds.length === 0 ? generatedComment : `${generatedComment}${YAML.stringify(ordered)}`;

  return writeFileIfChanged(filePath, content);
}

export default writeModuleLockfile;
