// The token store of a bearer host that keeps its session token in memory
// only: the token is gone when the client is, and is never written to browser
// storage, a cookie or a URL.
function createMemoryTokenStore() {
  let token = null;
  return {
    get: () => token,
    set: (value) => {
      token = value;
    },
    clear: () => {
      token = null;
    },
  };
}

export default createMemoryTokenStore;
