// cyrb53 by bryc (public domain, github.com/bryc/code/blob/master/jshash/experimental/cyrb53.js):
// a fast 53-bit string hash over the UTF-16 code units of `text`. The Table computes the
// same hash in the browser while it renders, where SubtleCrypto (async) can not be used, so
// the two copies must stay identical: test/enrichmentInputHash.json pins them together.
function cyrb53(text, seed = 0) {
  let h1 = 0xdeadbeef ^ seed;
  let h2 = 0x41c6ce57 ^ seed;
  for (let index = 0; index < text.length; index += 1) {
    const code = text.charCodeAt(index);
    h1 = Math.imul(h1 ^ code, 2654435761);
    h2 = Math.imul(h2 ^ code, 1597334677);
  }
  h1 = Math.imul(h1 ^ (h1 >>> 16), 2246822507);
  h1 ^= Math.imul(h2 ^ (h2 >>> 13), 3266489909);
  h2 = Math.imul(h2 ^ (h2 >>> 16), 2246822507);
  h2 ^= Math.imul(h1 ^ (h1 >>> 13), 3266489909);
  return 4294967296 * (2097151 & h2) + (h1 >>> 0);
}

export default cyrb53;
