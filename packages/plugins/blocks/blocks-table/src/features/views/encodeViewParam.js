// A persisted view payload as a URL-safe query value: base64url of its UTF-8 JSON, which stays
// short and needs no percent-escaping.
function encodeViewParam(payload) {
  const bytes = new TextEncoder().encode(JSON.stringify(payload));
  let binary = '';
  bytes.forEach((byte) => {
    binary += String.fromCharCode(byte);
  });
  return btoa(binary).replace(/\+/g, '-').replace(/\//g, '_').replace(/=+$/, '');
}

export default encodeViewParam;
