// A click with a modifier key or a button other than the main one asks the browser for a new tab
// or window, or a download; the layout leaves those alone.
function isPlainClick(event) {
  return (
    (event.button ?? 0) === 0 &&
    !event.metaKey &&
    !event.ctrlKey &&
    !event.shiftKey &&
    !event.altKey
  );
}

export default isPlainClick;
