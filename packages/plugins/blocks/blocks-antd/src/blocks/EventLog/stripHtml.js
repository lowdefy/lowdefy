import { type } from '@lowdefy/helpers';

// Plain text of a rich value, used for the row tooltip and the search blob. The result is only
// ever rendered as text - rich values are rendered as html by renderHtml, which sanitizes.
function stripHtml(html) {
  if (type.isNone(html)) return '';
  return String(html)
    .replace(/<[^>]*>/g, ' ')
    .replace(/&nbsp;/g, ' ')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&#39;/g, "'")
    .replace(/&quot;/g, '"')
    .replace(/&amp;/g, '&')
    .replace(/\s+/g, ' ')
    .trim();
}

export default stripHtml;
