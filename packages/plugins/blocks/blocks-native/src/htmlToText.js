import { type } from '@lowdefy/helpers';

const entities = {
  '&amp;': '&',
  '&lt;': '<',
  '&gt;': '>',
  '&quot;': '"',
  '&#39;': "'",
  '&nbsp;': ' ',
};

// Text properties that "support html" on the web are shown as plain text on a phone: line breaks
// and paragraph ends become new lines, other tags are dropped and the common entities decoded.
function htmlToText(html) {
  if (!type.isString(html)) {
    return html;
  }
  return html
    .replace(/<br\s*\/?>/gi, '\n')
    .replace(/<\/p>\s*<p[^>]*>/gi, '\n')
    .replace(/<[^<>]*>/g, '')
    .replace(/&(amp|lt|gt|quot|#39|nbsp);/g, (entity) => entities[entity]);
}

export default htmlToText;
