import path from 'node:path';

const MIME_BY_EXTENSION = {
  '.bmp': 'image/bmp',
  '.gif': 'image/gif',
  '.jpeg': 'image/jpeg',
  '.jpg': 'image/jpeg',
  '.png': 'image/png',
  '.svg': 'image/svg+xml',
  '.webp': 'image/webp',
};

// A file on disk carries no content-type header, so its extension decides
// whether it is an image at all. Unknown extensions resolve to undefined.
function imageMimeOf(filePath) {
  return MIME_BY_EXTENSION[path.extname(filePath).toLowerCase()];
}

export default imageMimeOf;
