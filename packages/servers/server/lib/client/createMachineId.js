// A version 4 UUID built from crypto.getRandomValues. crypto.randomUUID exists only in a secure
// context (HTTPS or localhost), and apps are often served over plain HTTP on an internal network,
// where it is undefined (issue #1932). crypto.getRandomValues is available in every context.
function createMachineId() {
  const bytes = crypto.getRandomValues(new Uint8Array(16));
  // The version (4) and variant (10xx) bits, as crypto.randomUUID sets them.
  bytes[6] = (bytes[6] & 0x0f) | 0x40;
  bytes[8] = (bytes[8] & 0x3f) | 0x80;
  const hex = Array.from(bytes, (byte) => byte.toString(16).padStart(2, '0')).join('');
  return [
    hex.slice(0, 8),
    hex.slice(8, 12),
    hex.slice(12, 16),
    hex.slice(16, 20),
    hex.slice(20, 32),
  ].join('-');
}

export default createMachineId;
