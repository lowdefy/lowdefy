import fs from 'fs';
import path from 'path';
import { writeFile } from '@lowdefy/node-utils';
import collectBlockSourceContent from './collectBlockSourceContent.js';
import getTailwindThemeVars from './getTailwindThemeVars.js';

function buildThemeVars(tailwindConfig) {
  return getTailwindThemeVars({ tailwindConfig })
    .map(([name, value]) => `  ${name}: ${value};`)
    .join('\n');
}

// The deprecated public/styles.less is rejected by validateDeprecatedStyles,
// which runs before the build's error checkpoint - a config fault must not be
// discovered in the write phase.
async function writeGlobalsCss({ components, context }) {
  const tailwindConfig = components.theme?.tailwind;
  const themeVars = buildThemeVars(tailwindConfig);

  const userStylesAbsolute = path.join(context.directories.config, 'public/styles.css');
  const importUserStyles = fs.existsSync(userStylesAbsolute);

  let userStylesImport = '';
  if (importUserStyles) {
    const relPath = path
      .relative(context.directories.build, userStylesAbsolute)
      .split(path.sep)
      .join('/');
    userStylesImport = `/* User custom styles */\n@import "${relPath}" layer(components);\n\n`;
  }

  // All @import statements must precede @source and every other statement —
  // the CSS spec only allows @charset and empty @layer before @import, and
  // Vite's CSS pipeline enforces this (it warns and may drop late imports).
  const css = `/* Generated by Lowdefy build */

/* Layer order — locks cascade priority before Tailwind declares its own layers */
@layer theme, base, antd, components, utilities;

/* source(none) disables Tailwind's automatic source detection — without it the
   oxide scanner walks the entire server directory tree (node_modules and all,
   ~50s cold) on the first CSS compile. The explicit @source globs below are
   the only scan inputs Lowdefy needs. */
@import "tailwindcss" source(none);
@import "@lowdefy/layout/grid.css";
/* Styles for data-* attributes in HTML (data-tag, data-status, …), scoped to
   HTML that Lowdefy's HtmlComponent enhanced. */
@import "@lowdefy/block-utils/html.css";

/* Imported CSS file — when this changes, PostCSS re-runs and Tailwind re-scans @source.
   This import is the ONLY recompile trigger in dev: the @source .html files below are
   deliberately excluded from Vite's watcher (server.watch.ignored in the dev server's
   vite.config.js) because watched .html changes force full browser reloads. The JIT
   page builder touches this file whenever tailwind content changes. */
@import "./tailwind-candidates.css";

${userStylesImport}/* Content sources for Tailwind JIT — block JS content collected at build time */
@source "../lowdefy-build/tailwind/*.html";

/* Themed scrollbars — opts out of the browser default that clashes on dark surfaces,
   especially on Windows/Linux where scrollbars are always visible and native-chrome.
   Colors use antd CSS custom properties so they auto-swap with dark/light mode. */
@layer base {
  * {
    scrollbar-width: thin;
    scrollbar-color: var(--ant-color-border-secondary, rgba(0, 0, 0, 0.15)) transparent;
  }
  *::-webkit-scrollbar {
    width: 10px;
    height: 10px;
  }
  *::-webkit-scrollbar-track {
    background: transparent;
  }
  *::-webkit-scrollbar-thumb {
    background-color: var(--ant-color-border-secondary, rgba(0, 0, 0, 0.15));
    background-clip: padding-box;
    border: 2px solid transparent;
    border-radius: 10px;
  }
  *::-webkit-scrollbar-thumb:hover {
    background-color: var(--ant-color-text-tertiary, rgba(0, 0, 0, 0.45));
  }
  *::-webkit-scrollbar-corner {
    background: transparent;
  }
}

/* Antd-to-Tailwind theme bridge — extends default Tailwind theme with antd design tokens */
@theme inline {
${themeVars}
}
`;

  await context.writeBuildArtifact('globals.css', css);

  // Standalone layer order declaration — imported FIRST in the client entry
  // (client/main.jsx) so the cascade layer priority is locked
  // (antd > base/preflight) before antd's CSS-in-JS injects @layer antd {}
  // at runtime. Without this, antd wins the race and becomes the
  // lowest-priority layer.
  await context.writeBuildArtifact(
    'layer-order.css',
    '/* Generated by Lowdefy build */\n@layer theme, base, antd, components, utilities;\n'
  );

  await context.writeBuildArtifact(
    'tailwind-candidates.css',
    '/* Generated by Lowdefy build — rewritten on page changes to trigger CSS recompilation */\n'
  );

  for (const [pageId, content] of context.tailwindContentMap ?? []) {
    await writeFile(
      path.join(
        context.directories.server,
        'lowdefy-build',
        'tailwind',
        `${encodeURIComponent(pageId)}.html`
      ),
      '<!-- Generated by Lowdefy build -->\n' + content
    );
  }

  // Collect Tailwind class candidates from block plugin JS source files.
  // Resolves from the server directory so block packages are reachable regardless
  // of package manager (pnpm strict isolation, yarn PnP, npm hoisting).
  const blockContent = collectBlockSourceContent({
    components,
    serverDirectory: context.directories.server,
  });
  if (blockContent) {
    await writeFile(
      path.join(context.directories.server, 'lowdefy-build', 'tailwind', '_blocks.html'),
      '<!-- Block plugin JS content collected at build time -->\n' + blockContent
    );
  }
}

export default writeGlobalsCss;
