import fs from 'fs';
import path from 'path';

// Compiles build/reports/styles.css — the app's Tailwind + custom CSS, resolved
// statically so the reports plugin's Html renderer can apply class-based styles.
// The shipped client bundle is not readable in dev or on Vercel (see design §5),
// so the stylesheet must be a build artifact. build/ is the one directory present
// in dev, Docker, and Vercel alike, and the plugin reads it with
// readConfigFile('reports/styles.css').
//
// Inputs mirror writeGlobalsCss minus the antd token bridge: those utilities
// resolve to var(--ant-*) variables antd injects at browser runtime, so they are
// dead weight in a statically compiled sheet.
async function writeReportStyles({ components, context }) {
  // Imported lazily: @tailwindcss/node loads a heavy native module graph, so a
  // build that never compiles a report stylesheet (the common case — this step
  // is gated on the reports plugin) pays nothing to have this file in the graph.
  const { compile, Features } = await import('@tailwindcss/node');
  const { Scanner } = await import('@tailwindcss/oxide');

  const base = context.directories.build;

  const userStylesAbsolute = path.join(context.directories.config, 'public/styles.css');
  let userStylesImport = '';
  if (fs.existsSync(userStylesAbsolute)) {
    const relPath = path.relative(base, userStylesAbsolute).split(path.sep).join('/');
    userStylesImport = `@import "${relPath}" layer(components);\n`;
  }

  // source(none) disables Tailwind's automatic source scan; the explicit @source
  // glob below points at the same page/block content globals.css tracks, so dev
  // rebuilds pick up class changes on the same watch triggers.
  const inputCss = `/* Generated by Lowdefy build — report stylesheet */
@import "tailwindcss" source(none);
@import "@lowdefy/layout/grid.css";
${userStylesImport}@source "../lowdefy-build/tailwind/*.html";
`;

  const compiler = await compile(inputCss, { base, onDependency: () => {} });

  const rootSources =
    compiler.root === 'none'
      ? []
      : compiler.root === null
        ? [{ base, pattern: '**/*', negated: false }]
        : [{ ...compiler.root, negated: false }];
  const scanner = new Scanner({ sources: rootSources.concat(compiler.sources) });

  const candidates = compiler.features & Features.Utilities ? scanner.scan() : [];
  const css = compiler.build(candidates);

  await context.writeBuildArtifact('reports/styles.css', css);
}

export default writeReportStyles;
