import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

import readModuleLockfile from './readModuleLockfile.js';

function makeConfigDir() {
  return fs.mkdtempSync(path.join(os.tmpdir(), 'lowdefy-lock-'));
}

test('readModuleLockfile returns an empty object when the lockfile does not exist', async () => {
  const configDirectory = makeConfigDir();
  await expect(readModuleLockfile({ configDirectory })).resolves.toEqual({});
  fs.rmSync(configDirectory, { recursive: true });
});

test('readModuleLockfile returns an empty object when the lockfile is empty', async () => {
  const configDirectory = makeConfigDir();
  fs.writeFileSync(path.join(configDirectory, 'lowdefy-modules.lock.yaml'), '   \n');
  await expect(readModuleLockfile({ configDirectory })).resolves.toEqual({});
  fs.rmSync(configDirectory, { recursive: true });
});

test('readModuleLockfile returns an empty object when the lockfile has only comments', async () => {
  const configDirectory = makeConfigDir();
  fs.writeFileSync(path.join(configDirectory, 'lowdefy-modules.lock.yaml'), '# generated\n');
  await expect(readModuleLockfile({ configDirectory })).resolves.toEqual({});
  fs.rmSync(configDirectory, { recursive: true });
});

test('readModuleLockfile parses lock entries', async () => {
  const configDirectory = makeConfigDir();
  fs.writeFileSync(
    path.join(configDirectory, 'lowdefy-modules.lock.yaml'),
    [
      '# This file is generated by the Lowdefy build. Commit it.',
      'team-users:',
      '  source: github:acme/lowdefy-modules/team-users@main',
      '  ref: main',
      '  commit: 4f0a1c9b2e7d5a3f8c1b6e0d9a4f7c2b5e8d1a30',
      '  fetchedAt: 2026-08-30T09:14:22.183Z',
      '',
    ].join('\n')
  );

  await expect(readModuleLockfile({ configDirectory })).resolves.toEqual({
    'team-users': {
      source: 'github:acme/lowdefy-modules/team-users@main',
      ref: 'main',
      commit: '4f0a1c9b2e7d5a3f8c1b6e0d9a4f7c2b5e8d1a30',
      fetchedAt: '2026-08-30T09:14:22.183Z',
    },
  });
  fs.rmSync(configDirectory, { recursive: true });
});

test('readModuleLockfile throws a ConfigError when the lockfile is not a map', async () => {
  const configDirectory = makeConfigDir();
  fs.writeFileSync(path.join(configDirectory, 'lowdefy-modules.lock.yaml'), '- a\n- b\n');
  await expect(readModuleLockfile({ configDirectory })).rejects.toThrow(
    'lowdefy-modules.lock.yaml should be a map of module entry ids to lock entries.'
  );
  fs.rmSync(configDirectory, { recursive: true });
});

test('readModuleLockfile throws a ConfigError when the lockfile is invalid yaml', async () => {
  const configDirectory = makeConfigDir();
  fs.writeFileSync(path.join(configDirectory, 'lowdefy-modules.lock.yaml'), 'a:\n- b\n  c: :\n');
  await expect(readModuleLockfile({ configDirectory })).rejects.toThrow(
    'Could not parse lowdefy-modules.lock.yaml'
  );
  fs.rmSync(configDirectory, { recursive: true });
});
